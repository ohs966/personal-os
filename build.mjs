// Bundles the OS's own assistant code (docs/core.js) with the server and its shims into one Worker file.
// Run: node build.mjs   ->  dist/worker.js (wrangler deploys it as-is, no second bundling)
import { build } from "esbuild";

await build({
  entryPoints: ["server/worker.ts"],
  outfile: "dist/worker.js",
  bundle: true, format: "esm", platform: "neutral", target: "es2022", minify: false,
  banner: { js: `// GENERATED by build.mjs from docs/core.js + server/*. Edit those files, then run: node build.mjs\nvar location = { hash: "" };` },
  legalComments: "none", charset: "utf8",
});
console.log("built dist/worker.js");
